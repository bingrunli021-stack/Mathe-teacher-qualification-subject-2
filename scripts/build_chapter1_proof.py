def classify(text):
    t=text.strip()
    if t in ('记忆口诀','考点解读','易混辨析','知识延伸','备考点拨','「强化练习/参考答案」','「要点回顾」'): return 'callout'
    if re.match(r'^[一二三四五六七八九十]+、',t): return 'h2'
    if re.match(r'^（[一二三四五六七八九十]+）',t): return 'h3'
    if re.match(r'^\d+\.',t) and len(t)<38 and not any(x in t for x in '？?（('): return 'h4'
    if re.match(r'^[①-⑳]|^第[一二三四五六七八九十]+[，、]',t): return 'list'
    if re.match(r'^[A-D][.．、]',t): return 'option'
    return 'p'

def corrected_page(pdf,ocr_dir,review):
    raw=json.loads((ocr_dir/f'{pdf:03}.json').read_text())['lines']; rv=review.get(str(pdf),{})
    lines=[]
    for i,l in enumerate(raw):
        if i in rv.get('drop',[]): continue
        text=rv.get('corrections',{}).get(str(i),l['text'])
        x=min(q[0] for q in l['box'])
        for n,part in enumerate(text.split('\n')):
            lines.append({'i':i,'text':part.strip(),'x':x if n==0 else x+1,'confidence':l.get('confidence',1)})
    return lines

def page_items(pdf,start,end,ocr_dir,review):
    rv=review.get(str(pdf),{}); lines=corrected_page(pdf,ocr_dir,review)
    tables={t['start']:t for t in rv.get('tables',[])}
    table_ranges=[(t['start'],t['end']) for t in rv.get('tables',[])]
    figs={f['after']:f for f in rv.get('figures',[])}
    out=[]; current=None
    def flush():
      nonlocal current
      if current: out.append(current);current=None
    for l in lines:
      i=l['i']
      if not(start<=i<=end): continue
      if any(a<=i<=b for a,b in table_ranges):
        if i in tables:
          flush();t=tables[i];out.append({'type':'table','headers':t['headers'],'rows':t['rows'],'caption':t.get('source_form','教材表格')})
        continue
      t=l['text']; typ=classify(t)
      if typ in ('h2','h3','h4','callout','option'):
        flush();out.append({'type':typ,'text':t})
      elif typ=='list':
        flush();out.append({'type':'list','text':t})
      else:
        # OCR x positions distinguish an indented new paragraph from its wrapped continuation.
        if current and current['type']=='p' and l['x']<150:
          current['text']+=t
        else:
          flush();current={'type':'p','text':t}
      if i in figs:
        flush();f=figs[i];out.append({'type':'figure-note','caption':f['caption'],'text':f['text']})
    flush();return out

